""" 
Светофорчики
В подземелье M тоннелей и N перекрестков, каждый тоннель соединяет какие-то два перекрестка. 
Мышиный король решил поставить по светофору в каждом тоннеле перед каждым перекрестком. 
Напишите программу, которая посчитает, сколько светофоров должно быть установлено 
на каждом из перекрестков. 
Перекрестки пронумерованы числами от 1 до N.

Входные данные
Во входном файле INPUT.TXT записано два числа N и M (0 < N ≤ 100, 0 ≤ M ≤ N*(N-1)/2).
В следующих M строках записаны по два числа i и j (1 ≤ i,j ≤ N), которые означают, 
что перекрестки i и j соединены тоннелем. 
Можно считать, что любые два перекрестка соединены не более, чем одним тоннелем. 
Нет тоннелей от перекрестка i до него самого.

Выходные данные
В выходной файл OUTPUT.TXT вывести N чисел: 
k-ое число означает количество светофоров на k-ом перекрестке.

РЕШЕНИЕ через ИИ (в теории графов не силён).

Считать N и M.
Создать массив (или список) count[1..N], 
заполненный нулями — он будет хранить количество светофоров для каждого перекрёстка.
Для каждого из M тоннелей, соединяющего i и j:
увеличить count[i] на 1;
увеличить count[j] на 1.
Вывести count[1], count[2], ..., count[N] через пробел.
Сложность: O(N+M) — это отлично укладывается в ограничения.
"""


def solve():
    # Читаем N и M из одной строки
    n, m = map(int, input().split())

    # Массив для подсчёта светофоров (индексы 1..N, поэтому размер n+1)
    count = [0] * (n + 1)

    for _ in range(m):
        u, v = map(int, input().split())
        count[u] += 1
        count[v] += 1

    # Выводим количество светофоров для перекрёстков 1..N через пробел
    print(*(count[i] for i in range(1, n + 1)))


if __name__ == "__main__":
    solve()
