"""
Модуль суммы
(Время: 1 сек. Память: 16 Мб Сложность: 25%)
Дана последовательность целых чисел.
Требуется найти подпоследовательность заданной последовательности с максимальным модулем суммы входящих в нее чисел.
Напомним, что модуль целого числа x равняется x, если x ≥ 0 и -x, если x < 0.

Входные данные
Первая строка входного файла INPUT.TXT содержит натуральное число n (1 ≤ n ≤ 10000) - длину последовательности.
Во второй строке записаны n целых чисел, по модулю не превосходящих 10000.

Выходные данные
В первой строке выходного файла OUTPUT.TXT выведите длину k выбранной вами подпоследовательности.
Во второй строке должны быть записаны k различных чисел,
разделенных пробелами - номера выбранных членов последовательности.
"""
n = int(input())
a = list(map(int, input().split()))

# Собираем индексы положительных и отрицательных чисел
pos_indices = []
neg_indices = []

for i in range(n):
    if a[i] > 0:
        pos_indices.append(i + 1)  # индексы с 1
    elif a[i] < 0:
        neg_indices.append(i + 1)

# Суммы
sum_pos = sum(a[i - 1] for i in pos_indices)
sum_neg = sum(a[i - 1] for i in neg_indices)

# Выбираем лучший вариант
if abs(sum_pos) >= abs(sum_neg):
    result_indices = pos_indices
else:
    result_indices = neg_indices

# Вывод
print(str(len(result_indices)))
if result_indices:
    print(' '.join(map(str, result_indices)))

