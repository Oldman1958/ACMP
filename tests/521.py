""" 
Пасьянс старухи Шапокляк
На столе лежат колоды игральных карт. 
В самой тоненькой колоде – p карт, во второй – p+1, в третьей – p+2, …, в последней – k карт. 
Старуха Шапокляк раскладывает пасьянс. 
Беря в руки любую из колод, она, если число карт в ней четное, 
на место возвращает колоду, наполовину уменьшив число карт в ней (лишние убирает в ящик), 
а если количество карт в колоде нечетное, то утраивает их количество и добавляет еще одну карту, 
а уже тогда кладет колоду на стол (карт у нее в ящике для этой операции достаточно). 
Если в какой-то колоде остается две карты, она больше ее не трогает. 
Пасьянс сходится, если во всех колодах остается по две карты.

Требуется написать программу, которая определит сходится ли пасьянс, 
и если сходится – сколько раз должна старуха Шапокляк брать со стола карты.

Входные данные
Входной файл INPUT.TXT содержит 2 числа, записанные через пробел (2 ≤ p < k < 1000).

Выходные данные
Выходной файл OUTPUT.TXT должен содержать 0, если пасьянс не сходится, 
и, если сходится, количество «ходов» старухи Шапокляк.

РЕШЕНИЕ.
Это классическая задача на моделирование процесса с проверкой сходимости. 
Разберём логику, а потом дам готовый код на Python, который читает INPUT.TXT, 
считает ходы и пишет результат в OUTPUT.TXT.

Логика процесса
У нас есть колоды с количеством карт от p до k включительно. 
На каждом ходе Шапокляк выбирает любую колоду 
(в задаче не сказано, какую именно, но пасьянс «сходится», если можно добиться состояния, 
когда во всех колодах по 2 карты).
Однако в таких задачах обычно подразумевается, что процесс детерминирован: 
мы просто применяем правило к каждой колоде независимо, пока она не станет равна 2.

Правило:

Если в колоде чётное число карт: делим пополам (убираем половину).
Если нечётное: делаем x→3x+1.
Если стало ровно 2 — колоду больше не трогаем.
Пасьянс сходится, если каждая колода из начального диапазона (p,p+1,…,k) 
рано или поздно приходит к 2 и не застревает в другом цикле.

Заметим, что операция x→3x+1 для нечётных и x→x/2 для чётных очень похожа 
на шаги гипотезы Коллатца, только с другим условием остановки (не 1, а 2). 
Нам нужно проверить, что для каждого начального значения от p до k последовательность 
действительно приходит к 2, и посчитать общее количество применений правил (ходов) по всем колодам.

Важные моменты

Независимость колод. 

Поскольку операции над одной колодой не влияют на другие, можно для каждого числа x из [p,k] 
отдельно промоделировать процесс и посчитать, сколько шагов нужно, чтобы дойти до 2. 
Если хотя бы одна колода не приходит к 2 
(например, уходит в бесконечный цикл или растёт без остановки), то пасьянс не сходится.

Ограничение на зацикливание. 

Чтобы не зациклиться, нужно детектировать циклы. 
Если в процессе обработки одного числа мы снова встречаем уже виденное значение — значит,
цикл есть, и до 2 не дойти. В таком случае пасьянс не сходится.

Границы. 

По условию 2≤p<k<1000, поэтому числа небольшие, и моделирование будет быстрым.
"""


def steps_to_two(start):
    """Возвращает количество шагов до 2 или None, если не приходит к 2."""
    x = start
    visited = set()
    steps = 0

    while x != 2:
        if x in visited:
            # Цикл: не придёт к 2
            return None
        visited.add(x)

        if x % 2 == 0:
            x //= 2
        else:
            x = 3 * x + 1

        steps += 1

    return steps


def solve():
    # Ввод из консоли: два числа через пробел
    data = input().strip().split()
    p = int(data[0])
    k = int(data[1])

    total_moves = 0

    for x in range(p, k + 1):
        s = steps_to_two(x)
        if s is None:
            print(0)
            return
        total_moves += s

    print(total_moves)


if __name__ == "__main__":
    solve()
