""" 
Премия

Несмотря на кризис, компания Soft-Soft работает успешно. 
Директор компании принял решение выплатить сотрудникам премии. 
На следующий день был обнародован список счастливчиков. 
Чтобы не разглашать размер выплат, в списке напротив фамилий красовались странные цифры 
и даже буквы. 
Сотрудники быстро догадались, что размер премий записан в различных системах счисления. 
Но где и какая система счисления используется, сообразила только секретарша Танечка, 
которая вспомнила, что директор просил ее принести информацию о возрасте сотрудников. 
Она поняла, что директор отбрасывал десятки из числа, указывающего возраст, 
а к оставшимся единицам добавлял число 2. 
Полученное значение служило основанием для представления начисленной премии.

Помогите любопытной Танечке узнать размер премий в десятичной системе счисления. 
Известно, что размер премий не превышает 100000 рублей в десятичной системе счисления.

Входные данные
В первой строке входного файла INPUT.TXT записаны два целых числа 
N и K – возраст и размер премии, 
разделенные пробелом.
Возраст не превышает 100, размер премии указан в некоторой системе счисления 
(запись числа не содержит незначащих нулей, использует арабские цифры 
и заглавные английские буквы).

Выходные данные
В выходной файл OUTPUT.TXT выведите одно число – размер премии в десятичной системе счисления.

РЕШЕНИЕ

Логика решения
Основание системы счисления вычисляется так:
Берём возраст N.
Отбрасываем десятки: это остаток от деления на 10, то есть N % 10.
Прибавляем 2: основание b=(Nmod10)+2.
Размер премии K дан как строка в системе счисления с основанием b. 
Нужно перевести её в десятичную систему.
В записи числа могут быть:
цифры 0–9;
заглавные буквы A–Z, где A = 10, B = 11, …, Z = 35.
Гарантируется, что результат не превысит 100 000.
"""


def char_to_value(ch: str) -> int:
    if '0' <= ch <= '9':
        return ord(ch) - ord('0')
    return ord(ch) - ord('A') + 10


n_age, k_str = input().split()
n_age = int(n_age)

base = (n_age % 10) + 2

value = 0
for ch in k_str:
    digit = char_to_value(ch)
    value = value * base + digit

print(value)
