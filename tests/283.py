""" 
Рунные слова
Руны — это древние магические знаки, которые наши предки использовали как буквы. 
Говорят, что рунные знаки обладают магическими свойствами, 
а при сложении рун в слова их магическая сила многократно возрастает. 
Если кузнец изготовит доспехи и начертит там определенные руны в определенном порядке, 
то доспехи будут наделены необычайными магическими силами.

Для того, чтобы стать обладателем таких доспехов 
достаточно просто принести кузнецу начертания этих рунных знаков. 
А вот, чтобы стать обладателем рунного знака приходилось немало потрудиться. 
Воины добывали начертания рун других языков и наречий в боях 
или получали их в качестве наград в благодарность за оказанные услуги.

Но так или иначе и в этом деле развелись жулики. 
По подозрениям ученых кузнец Игнатус Мошеникус 
изготавливал благородным воинам фальшивые рунные слова.
Из древних преданий ученым стало достоверно известно, 
что каждая руна записывается из двух, трех или четырех английских букв. 
Причем первая буква рунного слова всегда записывается как заглавная, 
а все остальные являются маленькими.
Ученые перевели несколько рунных слов, выкованных этим кузнецом, на английский язык 
и теперь нуждаются в Вашей помощи. Проверьте, является ли приведенное слово рунным.

Входные данные
В единственной строке входного файла INPUT.TXT содержится слово. 
Оно представляет собой непустую строку, длиной не более 100000 символов, 
содержащую только большие и маленькие буквы английского алфавита.

Выходные данные
В выходной файл OUTPUT.TXT выведите «Yes», если слово является рунным и «No» в противном случае.
"""


def is_valid_rune(sub: str) -> bool:
    length = len(sub)
    if length < 2 or length > 4:
        return False
    if not sub[0].isupper():
        return False
    for ch in sub[1:]:
        if not ch.islower():
            return False
    return True


s = input().strip()
n = len(s)
dp = [False] * (n + 1)
dp[0] = True

for i in range(1, n + 1):
    for length in (2, 3, 4):
        if i >= length:
            start = i - length
            sub = s[start:i]
            if is_valid_rune(sub) and dp[start]:
                dp[i] = True
                break

print("Yes" if dp[n] else "No")
