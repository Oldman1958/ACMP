""" 
Странная лотерея
(Время: 1 сек. Память: 16 Мб Сложность: 25%)
В честь успешного окончания первой четверти родители Пети и Вовы подарили им один лотерейный билет. 
Как обычно, ребята всерьез не восприняли данный подарок ввиду довольно скудной вероятности выигрыша по их мнению. 
Но каково было удивление братьев, когда они узнали из средств массовой информации, что номер их билета является выигрышным.

После продолжительных минут радости ребята бросились узнавать сумму выигрыша, но как оказалось, узнать это не так уж просто. 
Дело в том, что сумма выигрыша отчасти определяется самим владельцем или владельцами (если их несколько) следующим образом. 
На обратной стороне билета есть определенная секция, стерев слой защитного покрытия, можно увидеть целое положительное число N. 
После чего, каждый из владельцев билета должен зачеркнуть ровно по одной цифре данного числа N, 
полученное число и является суммой выигрыша.

Ниже приведен пример с N равным 995051.

Странная лотерея
Максимальное число, которое может быть получено из данного N посредством вычеркивания двух цифр является 9955. 
Помогите Пете и Вове в этой непростой, но очень актуальной для них задачей.

Входные данные
В единственной строке входного файла INPUT.TXT находится число N (100 ≤ N < 10250). Число не содержит лидирующих нулей. 
Строка входного файла заканчивается переводом строки и не содержит символов отличных от "0"-"9".

Выходные данные
В выходной файл OUTPUT.TXT выведите одно число – максимальное значение, 
которое может быть получено из N посредством вычеркивания из него ровно двух цифр.

РЕШЕНИЕ
Чтобы число было максимальным, нужно, чтобы старшие (левые) разряды были как можно больше. Поэтому действуем жадно:

Первый проход: ищем первую позицию, где цифра меньше следующей, и удаляем её. 
Если такой нет (число неубывающее, например 777 или 54321), удаляем последнюю цифру.
Второй проход: повторяем ту же логику для уже изменённой строки — удаляем ещё одну цифру по тому же правилу.
Это работает, потому что удаление «мелкой» цифры раньше (левее) даёт больший выигрыш в значении числа, 
чем любые манипуляции правее.

Было лень возиться, поэтому решение из ИИ.
"""

s = input().strip()

# Удаляем первую цифру
for i in range(len(s) - 1):
    if s[i] < s[i + 1]:
        s = s[:i] + s[i+1:]
        break
else:
    s = s[:-1]

# Удаляем вторую цифру
for i in range(len(s) - 1):
    if s[i] < s[i + 1]:
        s = s[:i] + s[i+1:]
        break
else:
    s = s[:-1]

print(s)
