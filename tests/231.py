""" 
Распаковка строки
(Время: 1 сек. Память: 16 Мб Сложность: 25%)
Будем рассматривать только строчки, состоящие из заглавных английских букв.
Например, рассмотрим строку AAAABCCCCCDDDD. Длина этой строки равна 14.
Поскольку строка состоит только из английских букв, повторяющиеся символы могут быть удалены и заменены числами, 
определяющими количество повторений. 
Таким образом, данная строка может быть представлена как 4AB5C4D. 
Длина такой строки 7. Описанный метод мы назовем упаковкой строки.

Напишите программу, которая берет упакованную строчку и восстанавливает по ней исходную строку.

Входные данные
Входной файл INPUT.TXT содержит одну упакованную строку.
В строке могут встречаться только конструкции вида nA, где n — количество повторений символа (целое число от 2 до 99), 
а A — заглавная английская буква, либо конструкции вида A, то есть символ без числа, определяющего количество повторений. 
Строка содержит от 1 до 80 символов.

Выходные данные
В выходной файл OUTPUT.TXT выведите восстановленную строку. 
При этом строка должна быть разбита на строчки длиной ровно по 40 символов (за исключением последней, 
которая может содержать меньше 40 символов).
"""


s = input().strip()
res = ''
i = 0

while i < len(s):
    if s[i].isdigit():
        # Собираем число (может быть 2–99)
        num = 0
        while i < len(s) and s[i].isdigit():
            num = num * 10 + int(s[i])
            i += 1
        # Добавляем букву нужное число раз
        res += s[i] * num
        i += 1
    else:
        # Одиночная буква — просто добавляем её
        res += s[i]
        i += 1

# Выводим по 40 символов в строке
for k in range(0, len(res), 40):
    print(res[k:k+40])
