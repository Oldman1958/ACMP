"""
Несложная сортировка
(Время: 1 сек. Память: 16 Мб Сложность: 25%)
Пусть x – целое положительное число, а k – натуральное число от 2 до 10.
Пусть s(x, k) равно сумме цифр числа x, представленного в системе счисления по основанию k.

Задано n чисел a1, a2, ..., an.
Необходимо вычислить последовательность bi по формуле bi = s(ai, k1) • s(ai, k2),


после чего отсортировать последовательность bi по неубыванию.

Входные данные
Первая строка входного файла INPUT.TXT содержит три целых числа: n, k1, k2 (1 ≤ n ≤ 1000, 2 ≤ k1, k2 ≤ 10).
Вторая строка содержит n целых чисел: ai (1 ≤ ai ≤ 109).

Выходные данные
В выходной файл OUTPUT.TXT выведите n чисел – bi в требуемом порядке.

Разбор задачи
Нужно:

Для каждого числа aᵢ из входных данных вычислить bᵢ = s(aᵢ,k₁)·s(aᵢ,k₂), где
s(x,k)—сумма цифр числа x в системе счисления с основанием k.

Отсортировать получившиеся bᵢ по неубыванию (от меньшего к большему).

Вывести отсортированный массив.

Алгоритм решения
Прочитать входные данные: n, k₁, k₂ и массив a.

Для каждого aᵢ:

Вычислить s(aᵢ,k₁).

Вычислить s(aᵢ,k₂).

Найти bᵢ=s(aᵢ,k₁)×s(aᵢ,k₂).

Отсортировать массив b по возрастанию.

Вывести отсортированный массив.
"""

def digit_sum(x, k):
    """Возвращает сумму цифр числа x в системе счисления с основанием k."""
    s = 0
    while x > 0:
        s += x % k
        x //= k
    return s

# Чтение входных данных
with open('INPUT.TXT', 'r') as f:
    n, k1, k2 = map(int, f.readline().split())
    a = list(map(int, f.readline().split()))

# Вычисление b_i
b = []
for ai in a:
    s1 = digit_sum(ai, k1)
    s2 = digit_sum(ai, k2)
    b.append(s1 * s2)

# Сортировка
b.sort()

# Запись результата
with open('OUTPUT.TXT', 'w') as f:
    f.write(' '.join(map(str, b)))