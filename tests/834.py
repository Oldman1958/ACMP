import math


def solve():
    # Ввод: первая строка — xk yk, вторая — xc yc rc
    line1 = input().strip().split()
    line2 = input().strip().split()

    xk, yk = map(float, line1)
    xc, yc, rc = map(float, line2)

    # Расстояние от места разговора до центра замка
    D = math.hypot(xk - xc, yk - yc)

    if D <= rc:
        # Точка внутри или на круге: выпуклая оболочка — это сам круг
        area = math.pi * rc * rc
    else:
        L = math.sqrt(D * D - rc * rc)          # длина касательной
        alpha = math.acos(rc / D)              # угол (в радианах)
        area = math.pi * rc * rc + rc * L - 2 * rc * rc * alpha

    print(f"{area:.5f}")  # выводим с запасом знаков, чтобы совпало с 5.69646


if __name__ == "__main__":
    solve()
